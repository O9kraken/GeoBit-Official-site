export async function up({ payload, req }: MigrateUpArgs): Promise<void> {
  for (const [slug, p] of Object.entries(PATCHES)) {
    const found = await payload.find({ collection: 'projects', where: { slug: { equals: slug } }, limit: 1, depth: 0, req })
    const doc: any = found.docs[0]
    if (!doc) continue
    const data: any = {}

    if (isEmpty(doc.excerpt) || String(doc.excerpt).split(/\s+/).length > 16) data.excerpt = p.excerpt
    if (p.challenge && isEmpty(doc.challenge)) data.challenge = p.challenge
    if (p.solution) {
      if (isEmpty(doc.solution)) data.solution = p.solution
      else if (p.solutionIfStartsWith && String(doc.solution).startsWith(p.solutionIfStartsWith)) data.solution = p.solution
    }
    if (p.results.length && !(doc.results || []).length) data.results = p.results.map(([value, label]) => ({ value, label }))

    const meta = doc.meta || {}
    const m: any = {}
    if (!meta.title) m.title = p.meta.title
    if (!meta.description) m.description = p.meta.description
    if (!meta.answer) m.answer = p.meta.answer
    if (!meta.focusKeyword) m.focusKeyword = p.meta.focus
    if (Object.keys(m).length) data.meta = { ...meta, ...m }

    if (p.mediaDesc && Array.isArray(doc.media)) {
      let changed = false
      const media = doc.media.map((it: any) => {
        const nd = p.mediaDesc![String(it.desc || '').trim()]
        if (nd) {
          changed = true
          return { ...it, desc: nd }
        }
        return it
      })
      if (changed) data.media = media
    }

    if (Object.keys(data).length) await payload.update({ collection: 'projects', id: doc.id, data, depth: 0, req })
  }

  // страница «Портфолио»: честный подзаголовок, ответ для поиска и свои вопросы
  const g: any = await payload.findGlobal({ slug: 'portfolio-page' as any, depth: 0, req })
  const gd: any = {}
  if (!g?.subtitle) gd.subtitle = 'Сайты, веб-приложения, логотипы и айдентика — с задачей, решением и результатом по каждому проекту'
  const seo = g?.seo || {}
  if (!seo.answer) {
    gd.seo = {
      ...seo,
      answer: 'В портфолио GeoBit — сайт кофейни «Кофе Бу» с электронным меню, логотипы для магазина автозапчастей AUTOBAHN и бренда одежды KODE23, айдентика сервисов baggyWEB и собственные веб-приложения NOIR RIVER и ZERO/STACK. По каждому кейсу описаны задача, решение и результат.',
    }
  }
  if (!(g?.faq || []).length) gd.faq = PORTFOLIO_FAQ.map(([q, a]) => ({ q, a }))
  if (Object.keys(gd).length) await payload.updateGlobal({ slug: 'portfolio-page' as any, data: gd, depth: 0, req })
}

